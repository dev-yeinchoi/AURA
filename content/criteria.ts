/** 맥락별 선정 기준 전문. S8/S10 의 "선정 기준 보기"에서 연다. */
export function selectionCriteria(risk: Risk): string {
  return risk === "low" ? LOW : HIGH;
}

/** S8/S10 좌측 상단 기준 요약 (docs/07 공통 레이아웃 원칙). */
export function criteriaSummary(risk: Risk): readonly string[] {
  const hours = risk === "low" ? "2시간" : "4시간";
  const unit = risk === "low" ? "회" : "건";
  return [
    `확보 가능 시간 주당 ${hours} 이상`,
    "최근 4건 중 3건 이상 기한 내 이행",
    `최근 수행 기록 6${unit} 중 5${unit} 이상`,
    `위 세 조건 충족 시, 관련 경험 6개월 이상 또는 수행 기록 6${unit} 모두 충족`,
    "나이는 판단 기준에 포함되지 않음",
    "적격 인원수 제한 없음",
  ];
}

